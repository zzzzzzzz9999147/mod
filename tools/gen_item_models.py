"""生成 Magic Induction 的物品模型 JSON。

为什么用脚本而不是手写：玻璃罐有 6 档内容变体（0-5 只蝴蝶），几何完全相同，
只有内容层贴图不同。手写 6 份 200 行的 elements 数组既容易抄错，也无法保证一致，
所以用 base 模型 + 子模型只覆盖 textures 的方式，由脚本生成。

坐标约定：block/item 模型的 16 单位坐标系，y=0 是罐底、y=15 是木塞顶。
"""

import json
import os

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(PROJECT_ROOT, "src", "main", "resources", "assets", "magicinduction")
MODELS = os.path.join(ASSETS, "models", "item")


def face(uv=(0, 0, 16, 16), tint=None):
    data = {"uv": list(uv), "texture": "#tex"}
    if tint is not None:
        data["tintindex"] = tint
    return data


def box(frm, to, tex, faces=("down", "up", "north", "south", "west", "east"),
        uv=(0, 0, 16, 16), shade=True):
    """一个长方体元素，六个面共用同一张贴图和同一块 UV。"""
    entry = {
        "from": list(frm),
        "to": list(to),
        "faces": {name: {"uv": list(uv), "texture": "#" + tex} for name in faces},
    }
    if not shade:
        entry["shade"] = False
    return entry


def jar_elements():
    """罐子的几何：罐身 -> 收肩 -> 瓶颈 -> 木塞 -> 内容薄片。

    内容层为什么是两片而不是一片：物品栏的默认展示姿态是 display.gui 的
    rotation [30, 225]，从这个角度看过来能看见的是模型的**北侧**。只画朝南的一片，
    在物品栏里就完全看不到罐内蝴蝶。所以南北各贴一片，各朝各的方向。
    罐身是实心盒（不是空壳），正好让两片薄片互不干扰——从任何一侧看，
    近的一片可见，远的一片被罐体挡掉。
    """
    return [
        # 罐身
        box((3.5, 0.0, 3.5), (12.5, 9.0, 12.5), "glass"),
        # 收肩，比罐身窄 1 单位，制造玻璃瓶的曲线轮廓
        box((4.5, 9.0, 4.5), (11.5, 11.0, 11.5), "glass"),
        # 瓶颈
        box((5.5, 11.0, 5.5), (10.5, 13.0, 10.5), "glass"),
        # 木塞
        box((5.0, 13.0, 5.0), (11.0, 15.0, 11.0), "cork"),
        # 内容薄片：南侧（朝外 +z）
        # UV 取 8x8 见方，对应薄片实际的 6.8 宽 x 7.4 高，宽高比接近 1:1，图案不变形。
        {
            "from": [4.6, 0.8, 12.52],
            "to": [11.4, 8.2, 12.72],
            "faces": {
                "south": {"uv": [4, 1, 12, 9], "texture": "#contents"},
            },
        },
        # 内容薄片：北侧（朝外 -z）
        {
            "from": [4.6, 0.8, 3.28],
            "to": [11.4, 8.2, 3.48],
            "faces": {
                "north": {"uv": [4, 1, 12, 9], "texture": "#contents"},
            },
        },
    ]


def jar_display():
    """六种展示姿态的变换。数值取自原版方块类物品的惯例（如 honey_block）。"""
    return {
        "thirdperson_righthand": {
            "rotation": [75, 45, 0], "translation": [0, 2.5, 0], "scale": [0.375, 0.375, 0.375],
        },
        "thirdperson_lefthand": {
            "rotation": [75, 45, 0], "translation": [0, 2.5, 0], "scale": [0.375, 0.375, 0.375],
        },
        "firstperson_righthand": {
            "rotation": [0, 45, 0], "scale": [0.4, 0.4, 0.4],
        },
        "firstperson_lefthand": {
            "rotation": [0, 225, 0], "scale": [0.4, 0.4, 0.4],
        },
        "ground": {
            "translation": [0, 3, 0], "scale": [0.25, 0.25, 0.25],
        },
        "gui": {
            "rotation": [30, 225, 0], "scale": [0.625, 0.625, 0.625],
        },
        "fixed": {
            "rotation": [0, 90, 0], "scale": [0.5, 0.5, 0.5],
        },
    }


def build_base():
    return {
        "credit": "Magic Induction - generated by tools/gen_item_models.py",
        "texture_size": [16, 16],
        "textures": {
            "glass": "magicinduction:item/jar_glass",
            "cork": "magicinduction:item/jar_cork",
            "contents": "magicinduction:item/jar_contents_0",
            "particle": "magicinduction:item/jar_glass",
        },
        "elements": jar_elements(),
        "display": jar_display(),
        "overrides": [
            {"predicate": {"butterflies": 1.0}, "model": "magicinduction:item/butterfly_jar_1"},
            {"predicate": {"butterflies": 2.0}, "model": "magicinduction:item/butterfly_jar_2"},
            {"predicate": {"butterflies": 3.0}, "model": "magicinduction:item/butterfly_jar_3"},
            {"predicate": {"butterflies": 4.0}, "model": "magicinduction:item/butterfly_jar_4"},
            {"predicate": {"butterflies": 5.0}, "model": "magicinduction:item/butterfly_jar_5"},
        ],
    }


def build_variant(count):
    """第 count 档内容子模型：只覆盖 contents 贴图，几何与展示姿态全部继承 base。"""
    if count == 0:
        return {"parent": "magicinduction:item/butterfly_jar_base"}
    return {
        "parent": "magicinduction:item/butterfly_jar_base",
        "textures": {"contents": f"magicinduction:item/jar_contents_{count}"},
    }


SPAWN_EGG_MODEL = {"parent": "minecraft:item/template_spawn_egg"}


def write(path, data):
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(data, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    print("wrote", os.path.relpath(path, PROJECT_ROOT))


def main():
    os.makedirs(MODELS, exist_ok=True)
    write(os.path.join(MODELS, "butterfly_jar_base.json"), build_base())
    for count in range(0, 6):
        name = "butterfly_jar.json" if count == 0 else f"butterfly_jar_{count}.json"
        write(os.path.join(MODELS, name), build_variant(count))
    write(os.path.join(MODELS, "mana_butterfly_spawn_egg.json"), SPAWN_EGG_MODEL)


if __name__ == "__main__":
    main()
